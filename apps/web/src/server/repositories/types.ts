/**
 * Repository interfaces — what the routes depend on.
 *
 * Routes never import Drizzle or the schema. They receive these interfaces, so moving
 * from SQLite to Neon (or faking the data in a test) means writing a new implementation,
 * not touching a route.
 */
import type {
  Card,
  CardPayment,
  Category,
  CategoryListItem,
  Month, MonthSummary, MonthTotals, Transaction, TransactionPage, TransactionQuery } from "../../shared/contracts";
import type { TransactionType } from "../db/schema";

export interface CreateTransactionData {
  type: TransactionType;
  amountMinor: number;
  description: string;
  categoryId: number;
  occurredOn: string;
  note: string | null;
  cardId: number | null;
}

export interface CategoryData {
  name: string;
  type: TransactionType;
  /** Parents only; null for a subcategory (it inherits). */
  color: string | null;
  parentId: number | null;
}

/** What happens to a parent's subcategories when it's deleted. */
export type ChildrenPlan = { moveTo: number } | { delete: true } | null;

export interface CategoryRepository {
  /** Every category with its transaction count, by type then name. */
  list(): Promise<CategoryListItem[]>;
  findById(id: number): Promise<CategoryListItem | undefined>;
  /** Exact name match within a type and parent (names are unique there). */
  findByName(name: string, type: TransactionType, parentId: number | null): Promise<Category | undefined>;
  create(data: CategoryData): Promise<CategoryListItem>;
  update(id: number, data: Partial<CategoryData>): Promise<CategoryListItem>;
  /**
   * Deletes the category in one DB transaction: first its subcategories are re-parented or deleted (`children`),
   * then its transactions and installment plans move to `moveTo` (if given).
   */
  remove(id: number, moveTo?: number, children?: ChildrenPlan): Promise<void>;
}

export interface TransactionRepository {
  /** One page of matching transactions, newest first, with the count and sums of all matches. */
  list(query: TransactionQuery): Promise<TransactionPage>;
  create(data: CreateTransactionData): Promise<Transaction>;
  findById(id: number): Promise<Transaction | undefined>;
  update(id: number, data: Partial<Omit<CreateTransactionData, "type">>): Promise<Transaction>;
  /** "installment": generated by a plan, so it can't be deleted on its own. */
  remove(id: number): Promise<"removed" | "missing" | "installment">;
}

export interface SummaryRepository {
  /** With `cardId`, only that credit card's charges. */
  forMonth(month: Month, cardId?: number): Promise<MonthSummary>;
  /** Income and expense per month for `months` months ending with `to`, oldest first; empty months are zeros. */
  monthly(to: Month, months: number, cardId?: number): Promise<MonthTotals[]>;
}

export type CardData = Omit<Card, "id" | "archived"> & { archived?: boolean };

/** Sums the statement math needs (see shared/cardCycle.ts), all for one card. */
export interface CardTotals {
  chargesToStatementMinor: number;
  paymentsToStatementMinor: number;
  paymentsAfterStatementMinor: number;
  chargesTotalMinor: number;
  paymentsTotalMinor: number;
  cycleSpendMinor: number;
  transactionCount: number;
}

export interface CardRepository {
  list(): Promise<Card[]>;
  findById(id: number): Promise<Card | undefined>;
  findByName(name: string): Promise<Card | undefined>;
  create(data: CardData): Promise<Card>;
  update(id: number, data: Partial<CardData>): Promise<Card>;
  /** Deletes the card and its payments. Callers make sure no transactions use it. */
  remove(id: number): Promise<void>;
  totals(id: number, dates: { statementDate: string; cycleFrom: string; today: string }): Promise<CardTotals>;
  payments(cardId: number): Promise<CardPayment[]>;
  addPayment(cardId: number, data: { amountMinor: number; paidOn: string; note: string | null }): Promise<CardPayment>;
  /** False when that payment doesn't exist on that card. */
  removePayment(cardId: number, paymentId: number): Promise<boolean>;
}

export interface Repositories {
  categories: CategoryRepository;
  transactions: TransactionRepository;
  summary: SummaryRepository;
  cards: CardRepository;
  installments: InstallmentRepository;
}

/** An installment plan as stored (terms only), with its category. */
export interface InstallmentRow {
  id: number;
  cardId: number;
  description: string;
  category: Category;
  purchasedOn: string;
  principalMinor: number;
  months: number;
  addOnRateBps: number;
  amortizationMinor: number | null;
  feeMinor: number;
  firstBillingMonth: string;
  preterminatedOn: string | null;
}

export type InstallmentData = Omit<InstallmentRow, "id" | "cardId" | "category"> & { categoryId: number };

export interface InstallmentRepository {
  listForCard(cardId: number): Promise<InstallmentRow[]>;
  countForCategory(categoryId: number): Promise<number>;
  findById(id: number): Promise<InstallmentRow | undefined>;
  create(cardId: number, data: InstallmentData): Promise<number>;
  update(id: number, data: Partial<InstallmentData>): Promise<void>;
  /** Deletes the plan; its generated expenses go with it (ON DELETE cascade). */
  remove(id: number): Promise<void>;
  /** Creates the expense for every billed schedule entry that doesn't exist yet (idempotent). */
  sync(today: string): Promise<void>;
  /** Deletes the plans' generated expenses and creates them again from the current terms. */
  regenerate(ids: number[], today: string): Promise<void>;
}
